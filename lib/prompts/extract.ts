/**
 * 온톨로지 어휘를 프롬프트에 넣어 '자유 서술' 대신 '선택'하게 한다.
 *
 * 왜 필요한가 —
 *   LLM 은 "컴포넌트 설계 표준화", "디자인 시스템 구축" 처럼 서술형으로 스킬명을 뽑는다.
 *   우리 온톨로지는 "컴포넌트 설계", "디자인 시스템" 같은 정규화된 명사라 매칭에 실패한다.
 *   실측: 이력서에 명시된 역량 3개(컴포넌트 설계·디자인 시스템·개발 핸드오프)를 전부 놓쳤다.
 *   → 선택지를 주면 표기가 일치해 매칭률이 올라간다.
 */
export function buildVocabularySection(skillNames: string[]): string {
  return `

## 사용할 역량 어휘

아래 목록에 있는 표기를 **그대로** 사용하세요. 목록에 없는 역량은 넣지 마세요.
표현이 달라도 뜻이 같으면 목록의 표기로 바꿔 적습니다.
  예) "컴포넌트 설계를 표준화" → "컴포넌트 설계"
      "디자인 시스템을 구축"   → "디자인 시스템"

${skillNames.join(' · ')}`;
}

/**
 * 코드가 먼저 찾아낸 후보를 프롬프트에 넣는다.
 *
 * 왜 —
 *   LLM 하나에게 '빠짐없이 찾기'와 '맞는지 판단하기'를 같이 시키면 둘 다 놓친다.
 *   실측: 나열형 이력서에서 iOS 누락. 상위 모델로 바꾸니 이번엔 Swift 누락.
 *   사전에 있는 이름을 원문에서 찾는 일은 판단이 아니라 대조다 — 코드가 하면 안 빠뜨린다.
 *   LLM 은 "이게 정말 이 사람의 역량인가"만 본다. 그건 코드가 못 한다.
 */
export function buildMentionSection(
  mentions: { name: string; matched: string; context: string }[]
): string {
  if (!mentions.length) return '';
  const lines = mentions
    .map((m) => `- ${m.name}   (원문: "${m.matched}")   …${m.context}…`)
    .join('\n');
  return `

## 원문에서 기계가 찾아낸 후보 (${mentions.length}개)

아래는 **이력서 원문에 그 글자가 실제로 있는 것**입니다. 찾는 일은 이미 끝났습니다.
당신이 할 일은 **거르는 것**입니다.

${lines}

### 이 목록을 어떻게 쓰나

1. **하나씩 판단하세요.** 개수가 많다는 이유로 임의로 줄이지 마세요.
2. **빼야 하는 경우** — 아래에 해당하면 skillCandidates 에 넣지 마세요.
   - 그 사람이 한 일이 아니다 (회사 소개·팀 소개·다른 직무 설명)
   - 하고 싶다는 말이다 (관심 있음·배우는 중·희망)
   - 남이 한 일이다 ("동료가 …", "우리 팀은 …")
   - 문맥이 다른 뜻이다 (예: 광고 지표 CPA 는 회계사 자격증이 아니다)
3. **뺀 것은 그냥 빼세요.** 왜 뺐는지 설명하지 마세요.
4. 목록에 없어도 **'일하는 방식'은 원문을 읽고 추가로 뽑으세요** — 도구 이름이 아니라
   요구사항 정의·이해관계자 조율처럼 행위로 적힌 것입니다. 기계는 이걸 못 찾습니다.`;
}

export function buildExtractUserPrompt(
  resumeText: string, targetJob?: string, vocabulary?: string, mentions?: string
): string {
  const target = targetJob
    ? `\n\n## 참고\n사용자가 관심 있다고 밝힌 직무: ${targetJob}\n(이 정보로 추출 결과를 왜곡하지 마세요. 없는 스킬을 만들어내면 안 됩니다.)`
    : '';

  return `다음 이력서에서 역량을 추출하세요.

## 이력서
"""
${resumeText}
"""${target}${vocabulary ?? ''}

JSON만 출력하세요.`;
}

